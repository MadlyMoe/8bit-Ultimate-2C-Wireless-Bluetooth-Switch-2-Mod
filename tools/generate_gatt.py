"""Generate the complete Pro2 handle layout for the bounded ATT server.

Pure source generation; no firmware patch or device access. The audio-shaped
attributes preserve the updated profile's handle map; their writes must be
rejected by the target because the Wireless controller has no headset hardware.
"""
import json
import uuid
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generate():
    model=json.loads((ROOT/'firmware/pro2-profile.json').read_text())
    lines=['/* SPDX-License-Identifier: MIT; generated by tools/generate_gatt.py. */',
           '#include "s2_gatt.h"']
    def constant(name,data):
        lines.append(f'static const uint8_t {name}[]={{'+','.join(f'0x{x:02x}' for x in data)+'};')
    for name,text in model['uuids'].items(): constant(name,uuid.UUID(text).bytes[::-1])
    for name,value in [('primary',0x2800),('declaration',0x2803),('cccd_uuid',0x2902),
                       ('gap',0x1800),('gatt',0x1801),('device_name',0x2a00),('appearance_uuid',0x2a01),('changed_uuid',0x2a05)]:
        constant(name,value.to_bytes(2,'little'))
    for props in (2,8,4,16,18,32): constant(f'props_{props}',bytes([props]))
    constant('name',b'8BitDo Ultimate 2C')
    constant('appearance',b'\xc4\x03')
    constant('empty',bytes(4))
    rows=[]
    def row(count,perm,ulen,length,key,value,write='0',read='0',label=''):
        dynamic=(write!='0' or read!='0')
        if dynamic: perm|=0x80; value='empty'
        rows.append(f'    {{{count},{perm},{ulen},{length},{key},{value}}}, /* 0x{len(rows)+1:04x} {label} */')
    def characteristic(key,props,length=0,value='empty',notify=False,descriptor=None):
        row(1,1,2,1,'declaration',f'props_{props}',label='declaration')
        permission=(1 if props&2 else 0)|(2 if props&12 else 0)
        row(1,permission,16,length,key,value,'s2_target_attribute_write' if props&12 else '0',
            's2_target_input_read' if key=='PRO2_INPUT_UUID' else '0',key)
        if notify:
            index=sum('cccd_uuid' in r for r in rows)
            row(1,3,2,2,'cccd_uuid',f's2_cccd[{index}]','s2_target_attribute_write',label='CCCD')
            row(1,3,16,2,descriptor,f's2_descriptors[{index}]','s2_target_attribute_write',label='vendor descriptor')
    row(7,1,2,16,'primary','SERVICE1_UUID',label='service 1')
    characteristic('SERVICE1_CHR_281_UUID',2)
    characteristic('SERVICE1_CHR_282_UUID',8)
    characteristic('SERVICE1_CHR_283_UUID',2)
    row(43,1,2,16,'primary','SERVICE2_UUID',label='service 2')
    characteristic('COMMON_INPUT_UUID',18,notify=True,descriptor='REPORT_RATE_DESC_UUID')
    characteristic('PRO2_INPUT_UUID',18,63,'s2_current_input',True,'REPORT_RATE_DESC_UUID')
    for name in ['VIBRATION_UUID','COMMAND_UUID','VIBRATION_COMMAND_UUID','FIRMWARE_UPDATE_UUID']:
        characteristic(name,4)
    for name in ['COMMAND_RESPONSE1_UUID','COMMAND_RESPONSE2_UUID','UNKNOWN_INPUT1_UUID']:
        characteristic(name,16,notify=True,descriptor='CMD_RESPONSE_DESC_UUID')
    characteristic('UNKNOWN_INPUT2_UUID',18,notify=True,descriptor='REPORT_RATE_DESC_UUID')
    characteristic('UNKNOWN_OUTPUT_UUID',4)
    characteristic('AUDIO_OUTPUT_UUID',4)
    characteristic('AUDIO_INPUT_UUID',18,notify=True,descriptor='REPORT_RATE_DESC_UUID')
    characteristic('AUDIO_COMMAND_UUID',4)
    row(5,1,2,2,'primary','gap',label='GAP')
    row(1,1,2,1,'declaration','props_2')
    row(1,1,2,len(b'8BitDo Ultimate 2C'),'device_name','name')
    row(1,1,2,1,'declaration','props_2')
    row(1,1,2,2,'appearance_uuid','appearance')
    row(4,1,2,2,'primary','gatt',label='GATT')
    row(1,1,2,1,'declaration','props_32')
    row(1,1,2,4,'changed_uuid','empty')
    row(1,3,2,2,'cccd_uuid','empty','dynamic',label='service changed CCCD')
    required={0xe:'PRO2_INPUT_UUID',0x14:'COMMAND_UUID',0x16:'VIBRATION_COMMAND_UUID',
              0x1a:'COMMAND_RESPONSE1_UUID',0x1e:'COMMAND_RESPONSE2_UUID',0x33:'GAP',0x38:'GATT'}
    if len(rows)!=59 or any(name not in rows[handle-1] for handle,name in required.items()):
        raise ValueError('Generated handles do not match the documented Pro2 layout')
    lines += ['const s2_gatt_attribute s2_attributes[]={','    {59,0,0,0,0,0}, /* table header */',*rows,'};','']
    return '\n'.join(lines)

if __name__=='__main__':
    path=ROOT/'firmware/target/pro2_gatt.c'
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(generate(),encoding='utf-8')
    print('Generated 59 GATT attributes; dynamic values belong to the bounded ATT server.')
